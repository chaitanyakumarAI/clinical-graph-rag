"""
pipeline/cypher_generator.py
Phase 3 — LLM-driven dynamic Cypher query generation.

Replaces (or augments) fixed Cypher templates with schema-aware,
context-specific queries generated by the LLM.

Safety rules enforced on all generated queries:
  - Must start with MATCH (read-only; no CREATE/DELETE/MERGE)
  - Must include LIMIT clause
  - Must include confidence filter WHERE r.confidence > 0.5
"""

from __future__ import annotations
import json
import os
import re
from typing import List, Dict, Optional, TYPE_CHECKING
from dotenv import load_dotenv

if TYPE_CHECKING:
    from graph.neo4j_client import Neo4jClient

load_dotenv()

_MAX_HOPS_DEFAULT = 3
_CONFIDENCE_MIN   = 0.5
_DEFAULT_LIMIT    = 25

SYSTEM_PROMPT_TEMPLATE = """You are an expert Neo4j Cypher query writer for a biomedical knowledge graph.

GRAPH SCHEMA:
{schema_text}

RULES (CRITICAL — violating these will cause errors):
1. Generate ONLY read-only Cypher. Start with MATCH. NEVER use CREATE, DELETE, MERGE, SET, REMOVE.
2. Always include LIMIT $limit at the end.
3. Always filter low-confidence edges: WHERE r.confidence > {confidence_min}
4. Use variable-length paths like [*1..{max_hops}] for multi-hop queries.
5. Use OPTIONAL MATCH for secondary traversals to avoid empty results.
6. Return these columns where applicable:
   - source, relation, target (for path results)
   - path_text (concatenated path as string)
   - confidence (edge confidence score)
   - sources, pages (provenance)
7. Generate up to 3 candidate queries, from most specific to most general.
   Return as a JSON array of query strings.

OUTPUT FORMAT:
{{
  "queries": [
    "MATCH (a:Drug {{name: $entity1}})-[r:TREATS]->(b:Disease) WHERE r.confidence > 0.5 RETURN a.name AS source, type(r) AS relation, b.name AS target, r.confidence AS confidence, r.sources AS sources, r.pages AS pages LIMIT $limit",
    "MATCH (a {{name: $entity1}})-[r]->(b) WHERE r.confidence > 0.5 RETURN a.name AS source, type(r) AS relation, b.name AS target, r.confidence AS confidence LIMIT $limit"
  ],
  "explanation": "First query targets drug-disease TREATS relationships; second is a general fallback."
}}"""

USER_PROMPT_TEMPLATE = """Generate Cypher queries to answer this medical question:

Question: {question}

Entities identified in the question:
{entities_text}

Route: {route}  (single_hop = 1 relationship; multi_hop = 2-3 relationships)

Generate 1-3 candidate Cypher queries, most specific first, general fallback last.
Use $entity1, $entity2, $entity3 as parameter placeholders for entity names.
Always include LIMIT $limit and confidence filters."""


# ── Safety validator ──────────────────────────────────────────────────────────

def _is_safe_cypher(query: str) -> bool:
    """
    Validate that a Cypher query is read-only and has required clauses.
    Returns True if safe to execute.
    """
    q = query.strip().upper()
    # Must start with MATCH or WITH
    if not (q.startswith("MATCH") or q.startswith("WITH") or q.startswith("CALL")):
        return False
    # Must not contain write operations
    write_ops = ["CREATE ", "DELETE ", "MERGE ", " SET ", "REMOVE ", "DROP "]
    if any(op in q for op in write_ops):
        return False
    # Must contain LIMIT
    if "LIMIT" not in q:
        return False
    return True


def _inject_limit_if_missing(query: str, limit: int) -> str:
    """Add LIMIT clause if not present."""
    if "LIMIT" not in query.upper():
        return f"{query.rstrip()} LIMIT {limit}"
    return query


# ── LLM calls ────────────────────────────────────────────────────────────────

def _call_groq(system: str, user: str) -> str:
    from groq import Groq
    client = Groq(api_key=os.getenv("GROQ_API_KEY"))
    resp = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[
            {"role": "system", "content": system},
            {"role": "user",   "content": user},
        ],
        response_format={"type": "json_object"},
        temperature=0.0,
        max_tokens=1024,
    )
    return resp.choices[0].message.content


def _call_openai(system: str, user: str) -> str:
    from openai import OpenAI
    client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))
    resp = client.chat.completions.create(
        model="gpt-4o",
        messages=[
            {"role": "system", "content": system},
            {"role": "user",   "content": user},
        ],
        response_format={"type": "json_object"},
        temperature=0.0,
        max_tokens=1024,
    )
    return resp.choices[0].message.content


# ── Main generator ────────────────────────────────────────────────────────────

def generate_cypher(
    question:        str,
    linked_entities: List[Dict],
    schema:          Dict,
    route:           str = "single_hop",
    provider:        str = "auto",
    max_hops:        int = _MAX_HOPS_DEFAULT,
    limit:           int = _DEFAULT_LIMIT,
) -> List[str]:
    """
    Generate schema-aware Cypher queries for a user question.

    Args:
        question:        User's medical question
        linked_entities: From entity_linker — list of {query_term, neo4j_name, ...}
        schema:          From schema_inspector.get_live_schema()
        route:           "single_hop" | "multi_hop"
        provider:        "auto" | "groq" | "openai"
        max_hops:        Max path depth for multi-hop queries
        limit:           LIMIT value injected into generated queries

    Returns:
        List of safe, ready-to-execute Cypher query strings (most specific first)
    """
    from graph.schema_inspector import format_schema_for_prompt

    schema_text  = format_schema_for_prompt(schema)
    entities_text = "\n".join(
        f"  - {e['query_term']} → Neo4j node: '{e['neo4j_name']}' "
        f"(label: {e.get('label', 'unknown')})"
        for e in linked_entities
    ) or "  (no specific entities identified)"

    system_prompt = SYSTEM_PROMPT_TEMPLATE.format(
        schema_text    = schema_text,
        confidence_min = _CONFIDENCE_MIN,
        max_hops       = max_hops,
    )
    user_prompt = USER_PROMPT_TEMPLATE.format(
        question     = question,
        entities_text = entities_text,
        route        = route,
    )

    try:
        if provider == "groq" or (provider == "auto" and os.getenv("GROQ_API_KEY")):
            raw = _call_groq(system_prompt, user_prompt)
        else:
            raw = _call_openai(system_prompt, user_prompt)

        data    = json.loads(raw)
        queries = data.get("queries", [])

    except Exception as e:
        print(f"[cypher_generator] LLM call failed: {e}")
        return []

    # Validate and clean
    safe_queries = []
    for q in queries:
        q = q.strip()
        q = _inject_limit_if_missing(q, limit)
        if _is_safe_cypher(q):
            safe_queries.append(q)
        else:
            print(f"[cypher_generator] ⚠️  Skipping unsafe query: {q[:80]}...")

    print(f"[cypher_generator] Generated {len(safe_queries)} safe queries "
          f"(from {len(queries)} candidates)")
    return safe_queries


def execute_first_nonempty(
    queries:    List[str],
    client:     "Neo4jClient",
    params:     Dict,
) -> List[Dict]:
    """
    Execute generated Cypher queries in order, return first non-empty result set.

    Args:
        queries: Ordered list of Cypher strings (most specific first)
        client:  Open Neo4jClient
        params:  Named parameters dict (entity1, entity2, limit, etc.)

    Returns:
        List of result row dicts, or [] if all queries return empty
    """
    for i, query in enumerate(queries):
        try:
            rows = client.run_query(query, params)
            if rows:
                print(f"[cypher_generator] Query {i+1}/{len(queries)} returned "
                      f"{len(rows)} rows ✅")
                return rows
            else:
                print(f"[cypher_generator] Query {i+1}/{len(queries)} returned 0 rows, trying next...")
        except Exception as e:
            print(f"[cypher_generator] Query {i+1} failed ({e}), trying next...")

    print("[cypher_generator] All generated queries returned empty results")
    return []
